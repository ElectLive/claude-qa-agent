// Self-test: proves the step templates embedded in .claude/agents/test-writer.md
// compile and run with runner-template/. Run from the repo root:
//   node scripts/selftest.mjs
// Builds a throwaway runner in .selftest/ (gitignored), serves a tiny demo app,
// and runs one UI scenario (+a11y, +visual baseline twice) and one API scenario.
import fs from 'fs';
import path from 'path';
import { execSync } from 'child_process';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, '.selftest');
const run = (cmd, env = {}) => execSync(cmd, { cwd: dir, stdio: 'inherit', env: { ...process.env, ...env } });

fs.rmSync(dir, { recursive: true, force: true });
fs.cpSync(path.join(root, 'runner-template'), dir, { recursive: true });

// 1. Templates come from test-writer.md: the single source of truth
const writer = fs.readFileSync(path.join(root, '.claude/agents/test-writer.md'), 'utf8');
const blocks = [...writer.matchAll(/```typescript\n([\s\S]*?)```/g)].map(m => m[1]);
if (blocks.length < 4) throw new Error(`expected 4 typescript blocks in test-writer.md, found ${blocks.length}`);
const [fixtures, common, api, perTest] = blocks;
fs.mkdirSync(path.join(dir, 'steps'), { recursive: true });
fs.writeFileSync(path.join(dir, 'steps/fixtures.ts'), fixtures);
fs.writeFileSync(path.join(dir, 'steps/common.steps.ts'), common);
fs.writeFileSync(path.join(dir, 'steps/api.steps.ts'), api);

const watermark = '🤖 Generated by DevOps QA Agent — review before relying on this test.';
for (const [name, src] of Object.entries({ fixtures, common, api, perTest })) {
  if (!src.includes(watermark)) throw new Error(`template "${name}" is missing the watermark header`);
}

// 2. Demo tests
const tc = path.join(dir, 'test-cases/selftest-0000-00-00');
fs.mkdirSync(tc, { recursive: true });
fs.writeFileSync(path.join(tc, 'Test#01.feature'), `# ${watermark}
Feature: Self-test UI

  @e2e @positive @visual
  Scenario: Submit button is clickable
    Given the user is on the "/" page
    When the user clicks the "Submit" button
    Then the page matches the "selftest-home" visual baseline
    And the page has no critical or serious accessibility violations
`);
fs.writeFileSync(path.join(tc, 'Test#01.steps.ts'), perTest);
fs.writeFileSync(path.join(tc, 'Test#02.feature'), `# ${watermark}
Feature: Self-test API

  @api @positive
  Scenario: Health endpoint returns fields
    Given the client is authenticated
    When the client sends GET "/health"
    Then the response status is 200
    And the response body has fields:
      | field  | type   |
      | status | string |
    And the response time is within the threshold
`);
fs.writeFileSync(path.join(tc, 'Test#02.steps.ts'), perTest);

// 3. Demo app
fs.writeFileSync(path.join(dir, 'server.cjs'), `require('http').createServer((q, r) => {
  if (q.url === '/health') { r.writeHead(200, { 'content-type': 'application/json' }); return r.end('{"status":"ok"}'); }
  r.writeHead(200, { 'content-type': 'text/html' });
  r.end('<!doctype html><html lang="en"><head><title>Self-test</title></head><body><main><h1>Self-test</h1><button>Submit</button></main></body></html>');
}).listen(4329);`);
const cfg = path.join(dir, 'playwright.config.ts');
fs.writeFileSync(cfg, fs.readFileSync(cfg, 'utf8').replace(
  "  projects: [",
  "  webServer: { command: 'node server.cjs', port: 4329 },\n  projects: [",
));

// 4. Run
const env = { BASE_URL: 'http://localhost:4329', API_BASE_URL: 'http://localhost:4329', API_TEST_TOKEN: 'selftest' };
run('npm install --no-audit --no-fund --silent');
run(`npx playwright install${process.env.CI && process.platform === 'linux' ? ' --with-deps' : ''} chromium`);
run('npx bddgen');
run('npx playwright test --project=api', { ...env, RUN_ID: 'api' });
// First visual run must fail with "snapshot doesn't exist" (baseline created); the second must pass
try { run('npx playwright test --project=e2e', { ...env, RUN_ID: 'e2e-1' }); } catch { /* expected */ }
const first = JSON.parse(fs.readFileSync(path.join(dir, 'runs/e2e-1/results.json'), 'utf8'));
if (!JSON.stringify(first).includes("A snapshot doesn't exist")) throw new Error('first visual run should create a baseline');
run('npx playwright test --project=e2e', { ...env, RUN_ID: 'e2e-2' });
if (!fs.readdirSync(path.join(dir, 'api-responses')).length) throw new Error('api fixture did not write an exchange file');
console.log('\n✅ self-test passed: templates compile, UI + a11y + visual + API scenarios run');
