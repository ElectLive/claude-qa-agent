#!/usr/bin/env bash
# Self-test: proves the Chainsaw templates embedded in .claude/agents/chainsaw-test-writer.md
# lint and pass against a real API server. Run from the repo root:
#   scripts/chainsaw-selftest.sh
# Needs: chainsaw, setup-envtest (or KUBEBUILDER_ASSETS with etcd/kube-apiserver/kubectl), openssl.
#   go install github.com/kyverno/chainsaw@v0.2.15
#   go install sigs.k8s.io/controller-runtime/tools/setup-envtest@release-0.21
# Starts its own throwaway etcd + kube-apiserver (RBAC on) in .selftest-chainsaw/ (gitignored):
# it never touches your kubeconfig's clusters. Then it checks each template fails when the
# behaviour it tests is broken, so a template that passes for the wrong reason is caught.
set -euo pipefail
root=$(cd "$(dirname "$0")/.." && pwd)
dir=$root/.selftest-chainsaw
agent=$root/.claude/agents/chainsaw-test-writer.md
K8S_VERSION=${K8S_VERSION:-1.33.x}

command -v chainsaw >/dev/null || { echo "✗ chainsaw not found (go install github.com/kyverno/chainsaw@v0.2.15)"; exit 1; }
command -v openssl >/dev/null || { echo "✗ openssl not found"; exit 1; }
if [ -z "${KUBEBUILDER_ASSETS:-}" ]; then
  command -v setup-envtest >/dev/null || { echo "✗ set KUBEBUILDER_ASSETS or install setup-envtest"; exit 1; }
  KUBEBUILDER_ASSETS=$(setup-envtest use "$K8S_VERSION" --bin-dir "$root/.selftest-chainsaw-bin" -p path)
fi
export PATH=$KUBEBUILDER_ASSETS:$PATH

rm -rf "$dir" && mkdir -p "$dir/tests" "$dir/kube"
pids=()
cleanup() { # SIGTERM, then SIGKILL whatever is still up after 10 s (kube-apiserver shuts down slowly)
  for p in "${pids[@]}"; do kill "$p" 2>/dev/null || true; done
  for _ in $(seq 10); do kill -0 "${pids[@]}" 2>/dev/null || return 0; sleep 1; done
  kill -9 "${pids[@]}" 2>/dev/null || true
}
trap cleanup EXIT

# 1. Control plane
cd "$dir/kube"
openssl genrsa -out sa.key 2048 2>/dev/null && openssl rsa -in sa.key -pubout -out sa.pub 2>/dev/null
echo 'selftest-admin-token,admin,admin,"system:masters"' > tokens.csv
etcd --data-dir etcd --listen-client-urls http://127.0.0.1:12379 --advertise-client-urls http://127.0.0.1:12379 \
  --listen-peer-urls http://127.0.0.1:12380 > etcd.log 2>&1 & pids+=($!)
kube-apiserver --etcd-servers=http://127.0.0.1:12379 --secure-port=16443 --bind-address=127.0.0.1 --cert-dir=certs \
  --authorization-mode=RBAC --token-auth-file=tokens.csv --service-account-issuer=https://kubernetes.default.svc \
  --service-account-key-file=sa.pub --service-account-signing-key-file=sa.key --service-cluster-ip-range=10.0.0.0/24 \
  --disable-admission-plugins=ServiceAccount > apiserver.log 2>&1 & pids+=($!)
cat > kubeconfig <<KC
apiVersion: v1
kind: Config
clusters: [{name: selftest, cluster: {server: https://127.0.0.1:16443, insecure-skip-tls-verify: true}}]
users: [{name: admin, user: {token: selftest-admin-token}}]
contexts: [{name: selftest, context: {cluster: selftest, user: admin}}]
current-context: selftest
KC
export KUBECONFIG=$dir/kube/kubeconfig
for _ in $(seq 60); do kubectl get --raw /readyz >/dev/null 2>&1 && break; sleep 1; done
kubectl get --raw /readyz >/dev/null || { tail -20 apiserver.log; echo "✗ API server didn't start"; exit 1; }
kubectl apply -f "$root/scripts/chainsaw-selftest/fixtures.yaml" >/dev/null
kubectl wait --for=condition=Established crd/widgets.qa.example.com --timeout=60s >/dev/null
sleep 2 # policy + RBAC caches

# 2. Templates come from the agent file: the single source of truth
awk -v out="$dir/tests" '
  /^<!-- file: .* -->$/ { f = $3; next }
  f && /^```yaml$/      { path = out "/" f; sub(/\/[^\/]*$/, "", path); system("mkdir -p \"" path "\""); cap = 1; next }
  cap && /^```$/        { cap = 0; f = ""; next }
  cap                   { print > (out "/" f) }
' "$agent"
n=$(find "$dir/tests" -name chainsaw-test.yaml | wc -l)
[ "$n" -ge 8 ] || { echo "✗ expected 8 templates in $agent, found $n"; exit 1; }
watermark='# 🤖 Generated by DevOps QA Agent — review before relying on this test.'
for f in "$dir/tests/.chainsaw.yaml" "$dir"/tests/Test*/chainsaw-test.yaml; do
  [ "$(head -1 "$f")" = "$watermark" ] || { echo "✗ $f: line 1 must be the watermark header"; exit 1; }
done

# 3. Lint
chainsaw lint configuration -f "$dir/tests/.chainsaw.yaml" >/dev/null
for f in "$dir"/tests/Test*/chainsaw-test.yaml; do chainsaw lint test -f "$f" >/dev/null || { echo "✗ lint: $f"; exit 1; }; done

# 4. Fake controller for the status template: marks any Widget named "reconciled" Ready
( while :; do
    kubectl get widgets -A -o jsonpath='{range .items[?(@.metadata.name=="reconciled")]}{.metadata.namespace}{"\n"}{end}' 2>/dev/null |
      while read -r ns; do [ -n "$ns" ] && kubectl -n "$ns" patch widget reconciled --subresource=status --type=merge \
        -p '{"status":{"conditions":[{"type":"Ready","status":"True","reason":"Reconciled"}]}}' >/dev/null 2>&1; done
    sleep 1
  done ) & pids+=($!)

run() { (cd "$dir/tests" && chainsaw test --config .chainsaw.yaml --test-dir "$1" --skip-delete --no-color 2>&1); }

# 5. Every template passes...
out=$(run .) || { echo "$out" | tail -40; echo "✗ templates failed against the fixture"; exit 1; }
echo "✓ $n templates pass"

# 6. ...and fails once the rule it checks is gone (catches tests that pass for the wrong reason)
mutate() { # <test dir> <description> <kubectl args…>
  local t=$1 what=$2; shift 2
  kubectl "$@" >/dev/null; sleep 2
  if (cd "$dir/tests" && chainsaw test --config .chainsaw.yaml --test-dir "$t" --skip-delete --assert-timeout 5s --no-color >/dev/null 2>&1); then echo "✗ $t still passes with $what"; exit 1; fi
  kubectl apply -f "$root/scripts/chainsaw-selftest/fixtures.yaml" >/dev/null; sleep 2
  echo "✓ $t fails with $what"
}
crd=(patch crd widgets.qa.example.com --type=json -p)
spec=/spec/versions/0/schema/openAPIV3Schema/properties/spec
mutate Test#01-widget-defaults-lifecycle "no default"  "${crd[@]}" "[{\"op\":\"remove\",\"path\":\"$spec/properties/tier/default\"}]"
mutate Test#02-widget-image-pattern     "no pattern"  "${crd[@]}" "[{\"op\":\"remove\",\"path\":\"$spec/properties/image/pattern\"}]"
mutate Test#03-widget-cel-maxreplicas   "no CEL rule" "${crd[@]}" "[{\"op\":\"remove\",\"path\":\"$spec/x-kubernetes-validations\"}]"
mutate Test#04-widget-owner-immutable   "a mutable owner" "${crd[@]}" "[{\"op\":\"remove\",\"path\":\"$spec/properties/owner/x-kubernetes-validations\"}]"
mutate Test#05-widget-size-policy       "no deny binding" delete validatingadmissionpolicybinding widget-size-cap
mutate Test#06-widget-bronze-warning    "no warn binding" delete validatingadmissionpolicybinding widget-bronze-deprecated
mutate Test#07-widget-viewer-rbac       "delete granted" patch clusterrole widget-viewer --type=json -p '[{"op":"add","path":"/rules/0/verbs/-","value":"delete"}]'
kill "${pids[-1]}" 2>/dev/null; unset 'pids[-1]'
if (cd "$dir/tests" && chainsaw test --config .chainsaw.yaml --test-dir Test#08-widget-ready-status --skip-delete --assert-timeout 5s --no-color >/dev/null 2>&1); then
  echo "✗ Test#08-widget-ready-status passes without a controller"; exit 1
fi
echo "✓ Test#08-widget-ready-status fails with no controller"
echo "✅ Chainsaw templates: lint, pass, and fail when their rule is removed"
